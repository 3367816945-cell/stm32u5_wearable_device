/**
  * @brief This function handles TIM3 global interrupt.
  */
void TIM3_IRQHandler(void)
{
  /* USER CODE BEGIN TIM3_IRQn 0 */
  unsigned char i = 0;
  unsigned int runningTotal;

  if (TIM3->SR & TIM_FLAG_UPDATE)
  {
      TIM3->SR = ~TIM_FLAG_UPDATE;

      Signal = HAL_ADC_GetValue(&hadc1) >> 2;
      sampleCounter += 2;
      Num = sampleCounter - lastBeatTime;

      if (Signal < thresh && Num > (IBI / 5) * 3)
      {
          if (Signal < T)
          {
              T = Signal;
          }
      }

      if (Signal > thresh && Signal > P)
      {
          P = Signal;
      }

      if (Num > 250)
      {
          if ((Signal > thresh) && (Pulse == 0) && (Num > (IBI / 5) * 3))
          {
              Pulse = 1;
              IBI = sampleCounter - lastBeatTime;
              lastBeatTime = sampleCounter;

              if (secondBeat)
              {
                  secondBeat = 0;
                  for (i = 0; i <= 9; i++)
                  {
                      rate[i] = IBI;
                  }
              }

              if (firstBeat)
              {
                  firstBeat = 0;
                  secondBeat = 1;
                  HAL_TIM_IRQHandler(&htim3);
                  return;
              }

              runningTotal = 0;
              for (i = 0; i <= 8; i++)
              {
                  rate[i] = rate[i + 1];
                  runningTotal += rate[i];
              }

              rate[9] = IBI;
              runningTotal += rate[9];
              runningTotal /= 10;
              BPM = 60000 / runningTotal;
              QS = 1;
          }
      }

      if (Signal < thresh && Pulse == 1)
      {
          Pulse = 0;
          amp = P - T;
          thresh = (amp >> 1) + T;
          P = thresh;
          T = thresh;
      }

      if (Num > 2500)
      {
          thresh = 512;
          P = 512;
          T = 512;
          lastBeatTime = sampleCounter;
          firstBeat = 1;
          secondBeat = 0;
          QS = 0;
      }

      HAL_TIM_IRQHandler(&htim3);
      return;
  }
  /* USER CODE END TIM3_IRQn 0 */
  HAL_TIM_IRQHandler(&htim3);
  /* USER CODE BEGIN TIM3_IRQn 1 */

  /* USER CODE END TIM3_IRQn 1 */
}

